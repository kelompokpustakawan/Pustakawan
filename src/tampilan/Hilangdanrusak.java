    private void bsimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bsimpanActionPerformed
    java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
    String tanggal = sdf.format(txtlapor.getDate());
    
    // Validasi input kosong
    if (txtpetugas.getText().isEmpty() || txtanggota.getText().isEmpty() || txtbuku.getText().isEmpty() || txtjumlah.getText().isEmpty() || txtdenda.getText().isEmpty()) {
        JOptionPane.showMessageDialog(null, "Semua data harus diisi!");
        return;
    }

    try {
        String sql = "INSERT INTO buku_rusak_hilang (tanggal_lapor, id_buku, id_anggota, id_petugas, jenis_kondisi, jumlah, denda_ganti_rugi, status_solusi) VALUES (?, ?, ?, ?, ?, ?, ?, ?)";
        PreparedStatement ps = conn.prepareStatement(sql);
        ps.setString(1, tanggal);
        ps.setInt(2, Integer.parseInt(txtbuku.getText()));
        ps.setInt(3, Integer.parseInt(txtanggota.getText()));
        ps.setInt(4, Integer.parseInt(txtpetugas.getText()));
        ps.setString(5, boxkondisi.getSelectedItem().toString());
        ps.setInt(6, Integer.parseInt(txtjumlah.getText()));
        ps.setInt(7, Integer.parseInt(txtdenda.getText()));
        ps.setString(8, boxstatus.getSelectedItem().toString());
        
        ps.executeUpdate();
        JOptionPane.showMessageDialog(null, "Data Berhasil Disimpan!");
        tampilkanData();
        kosongkanForm();
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(null, "Gagal menyimpan transaksi: " + e.getMessage());
    }
    }//GEN-LAST:event_bsimpanActionPerformed

