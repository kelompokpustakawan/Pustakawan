    private void tampilkanData() {
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID Kasus");
    model.addColumn("Tanggal Lapor");
    model.addColumn("ID Petugas");
    model.addColumn("ID Anggota");
    model.addColumn("ID Buku");
    model.addColumn("Kondisi");
    model.addColumn("Jumlah");
    model.addColumn("Denda Ganti Rugi");
    model.addColumn("Status Solusi");

    try {
        String sql = "SELECT * FROM buku_rusak_hilang ORDER BY id_kasus ASC";
        Statement st = conn.createStatement();
        ResultSet rs = st.executeQuery(sql);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("id_kasus"),
                rs.getString("tanggal_lapor"),
                rs.getString("id_petugas"),
                rs.getString("id_anggota"),
                rs.getString("id_buku"),
                rs.getString("jenis_kondisi"),
                rs.getString("jumlah"),
                rs.getString("denda_ganti_rugi"),
                rs.getString("status_solusi")
            });
        }
        tblhilang.setModel(model);
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage());
    }
}

